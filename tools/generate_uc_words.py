"""Turn game-art/table/undercover/words.txt into the firmware table (nabo_uc_words.c) and the
browser prototype's list (prototype/uc_words.js). Run after editing the word list, then
regenerate the fonts: the 24 px table font carries every character of every word."""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'game-art/table/undercover/words.txt'
BOARD = ROOT / 'xiaozhi-esp32/main/boards/folotoy/ai-passport-nabo'
PROTO = ROOT / 'game-art/table/prototype'


def load_pairs():
    pairs = []
    for n, line in enumerate(SOURCE.read_text('utf-8').splitlines(), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        words = line.split()
        if len(words) != 2 or words[0] == words[1]:
            raise SystemExit(f'{SOURCE.name}:{n}: need two different words')
        if any(len(w.encode('utf-8')) > 15 for w in words):
            raise SystemExit(f'{SOURCE.name}:{n}: word too long')
        pairs.append(words)
    dup = [w for w, c in Counter(w for p in pairs for w in p).items() if c > 1]
    if dup:
        raise SystemExit('words used twice: ' + ' '.join(dup))
    if not 32 <= len(pairs) <= 1000:
        raise SystemExit('need 32..1000 pairs')
    return pairs


def word_chars():
    return sorted({c for p in load_pairs() for w in p for c in w})


def main():
    pairs = load_pairs()
    rows = ',\n'.join(f'    {{{json.dumps(a, ensure_ascii=False)}, {json.dumps(b, ensure_ascii=False)}}}' for a, b in pairs)
    (BOARD / 'nabo_uc_words.c').write_text(
        '// Generated by tools/generate_uc_words.py from game-art/table/undercover/words.txt; do not edit.\n'
        '// Who is the undercover: word pairs, each word drawn with nabo_table_font_24.\n'
        '#include "nabo_uc_words.h"\n\n'
        f'const char *const NT_UC_WORDS[NT_UC_PAIRS][2] = {{\n{rows},\n}};\n', 'utf-8')
    (BOARD / 'nabo_uc_words.h').write_text(
        '#pragma once\n// Generated by tools/generate_uc_words.py; do not edit.\n'
        f'#define NT_UC_PAIRS {len(pairs)}\n'
        '#ifdef __cplusplus\nextern "C" {\n#endif\n'
        'extern const char *const NT_UC_WORDS[NT_UC_PAIRS][2];\n'
        '#ifdef __cplusplus\n}\n#endif\n', 'utf-8')
    (PROTO / 'uc_words.js').write_text(
        '// Generated by tools/generate_uc_words.py from game-art/table/undercover/words.txt; do not edit.\n'
        'const UC_WORDS = ' + json.dumps(pairs, ensure_ascii=False) + ';\n', 'utf-8')
    print(f'{len(pairs)} pairs, {len(word_chars())} distinct characters')


if __name__ == '__main__':
    main()
